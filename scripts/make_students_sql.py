"""Turn the exam seating Excel into a SQL file that fills the student roster.

Usage (from the project root):
    python scripts/make_students_sql.py data/seating-arrangement-sem1.xlsx

Writes supabase/students_seed.sql (git-ignored: it contains student names).
Paste that file into the Supabase SQL editor after running supabase/auth.sql.
Safe to re-run: it updates name/division but never touches `active` or a bound email.
"""
import re
import sys
from pathlib import Path

import openpyxl

OUT = Path("supabase/students_seed.sql")
BSP = re.compile(r"^\d{2}BSP\d{4}$")


def clean_name(raw: str) -> str:
    """'SWETHA RANI SWAMY (Not Allowed -Low Attendance)' -> 'Swetha Rani Swamy'."""
    return re.sub(r"\s+", " ", re.sub(r"\(.*?\)", "", raw)).strip().title()


def read_students(path: str) -> dict[str, tuple[str, str]]:
    students: dict[str, tuple[str, str]] = {}
    wb = openpyxl.load_workbook(path, read_only=True, data_only=True)
    for ws in wb.worksheets:
        for row in ws.iter_rows(values_only=True):
            bsp = str(row[2] or "").strip().upper()
            if not BSP.match(bsp):  # also skips title/header rows
                continue
            students.setdefault(bsp, (clean_name(str(row[3] or "")), str(row[5] or "").strip()))
    return students


def sql_str(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


def main() -> None:
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    students = read_students(sys.argv[1])
    if not students:
        sys.exit("No BSP numbers found. Is this the right file?")

    values = ",\n".join(
        f"  ({sql_str(bsp)}, {sql_str(name)}, {sql_str(div)}, true)"
        for bsp, (name, div) in sorted(students.items())
    )
    OUT.write_text(
        "-- Generated by scripts/make_students_sql.py. Contains student names: do not commit.\n"
        "insert into public.bsp_allowlist (bsp, name, division, active) values\n"
        f"{values}\n"
        "on conflict (bsp) do update set name = excluded.name, division = excluded.division;\n",
        encoding="utf-8",
    )
    print(f"Wrote {OUT} with {len(students)} students.")


if __name__ == "__main__":
    main()
